// Converts the Lucide icons the desktop app uses into one path string each, so the app draws
// them as geometry without a font or a CDN. Lucide is ISC-licensed; see THIRD-PARTY-NOTICES.md.
//
//   npm i --prefix .lucide lucide-static@0.460.0
//   node scripts/make-lucide-icons.mjs .lucide/node_modules/lucide-static/icons
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const icons = [
  "archive", "archive-restore", "boxes", "calendar-clock", "check", "chevron-down", "chevron-left",
  "chevron-right", "circle-help", "clock", "cloud", "copy", "external-link", "eye", "filter", "folder",
  "folder-open", "github", "hard-drive", "inbox", "info", "layout-dashboard", "loader", "lock", "minus",
  "monitor", "octagon-alert", "pause", "pencil", "plus", "refresh-cw", "rotate-ccw", "settings",
  "shield-check", "stethoscope", "trash-2", "triangle-alert", "unplug", "x",
];

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/make-lucide-icons.mjs <lucide-static/icons folder>");
  process.exit(1);
}

const num = (value) => Number.parseFloat(value ?? "0");
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

function rect(a) {
  const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
  const rx = Math.min(num(a.rx ?? a.ry), w / 2), ry = Math.min(num(a.ry ?? a.rx), h / 2);
  if (!rx) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
  return `M${x + rx} ${y}H${x + w - rx}A${rx} ${ry} 0 0 1 ${x + w} ${y + ry}V${y + h - ry}` +
    `A${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h}H${x + rx}A${rx} ${ry} 0 0 1 ${x} ${y + h - ry}` +
    `V${y + ry}A${rx} ${ry} 0 0 1 ${x + rx} ${y}Z`;
}

function ellipse(cx, cy, rx, ry) {
  return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
}

function points(list, close) {
  const values = list.trim().split(/[\s,]+/).map(Number);
  let d = "";
  for (let i = 0; i < values.length; i += 2) d += `${i ? "L" : "M"}${values[i]} ${values[i + 1]}`;
  return close ? d + "Z" : d;
}

// A path's leading "m" is absolute in SVG, but once paths are joined it would become relative to
// the previous one. Make it an explicit "M", and turn its trailing implicit pairs into "l".
function absoluteStart(d) {
  const number = "[-+]?(?:\\d+\\.?\\d*|\\.\\d+)(?:[eE][-+]?\\d+)?";
  const match = d.match(new RegExp(`^\\s*m\\s*(${number})[\\s,]*(${number})`));
  if (!match) return d;
  const rest = d.slice(match[0].length).trimStart();
  return `M${match[1]} ${match[2]}` + (/^[-+.\d]/.test(rest) ? `l${rest}` : rest);
}

function toPath(svg) {
  const parts = [];
  for (const [, tag, body] of svg.matchAll(/<(path|rect|circle|ellipse|line|polyline|polygon)\b([^>]*)\/?>/g)) {
    const a = attrs(body);
    switch (tag) {
      case "path": parts.push(absoluteStart(a.d)); break;
      case "rect": parts.push(rect(a)); break;
      case "circle": parts.push(ellipse(num(a.cx), num(a.cy), num(a.r), num(a.r))); break;
      case "ellipse": parts.push(ellipse(num(a.cx), num(a.cy), num(a.rx), num(a.ry))); break;
      case "line": parts.push(`M${a.x1} ${a.y1}L${a.x2} ${a.y2}`); break;
      case "polyline": parts.push(points(a.points, false)); break;
      case "polygon": parts.push(points(a.points, true)); break;
    }
  }
  return parts.join(" ");
}

const pascal = (name) => name.split("-").map((s) => s[0].toUpperCase() + s.slice(1)).join("");
const lines = icons.map((name) => {
  const d = toPath(readFileSync(join(source, `${name}.svg`), "utf8"));
  return `        ["${pascal(name)}"] = "${d}",`;
});

writeFileSync(
  "src/XIVault.Desktop/Controls/LucideIcons.cs",
  `// <auto-generated>
// Generated by scripts/make-lucide-icons.mjs from lucide-static 0.460.0 (ISC). Do not edit by hand.
// </auto-generated>
namespace XIVault.Desktop.Controls;

internal static class LucideIcons
{
    public static readonly IReadOnlyDictionary<string, string> Paths = new Dictionary<string, string>
    {
${lines.join("\n")}
    };
}
`);
console.log(`Wrote ${icons.length} icons`);
